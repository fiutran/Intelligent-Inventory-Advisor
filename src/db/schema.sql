-- Inventory Delta Advisor: backend schema (v2)
-- Includes frontend-aligned fields: provenance, aliases, decision snapshots.

CREATE TABLE "user" (
  user_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE category (
  category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT NOT NULL UNIQUE,
  icon        TEXT
);

CREATE TABLE preference_weight (
  user_id         INTEGER NOT NULL REFERENCES "user"(user_id) ON DELETE CASCADE,
  attribute       TEXT NOT NULL,
  weight          NUMERIC(8, 4) NOT NULL DEFAULT 0,
  evidence_count  INTEGER NOT NULL DEFAULT 0,
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, attribute)
);

CREATE TABLE keyword (
  keyword_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id  INTEGER NOT NULL REFERENCES category(category_id) ON DELETE CASCADE,
  word         TEXT NOT NULL,
  source       TEXT NOT NULL DEFAULT 'seed',
  UNIQUE (category_id, word)
);

CREATE TABLE inventory_item (
  item_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       INTEGER NOT NULL REFERENCES "user"(user_id) ON DELETE CASCADE,
  category_id   INTEGER NOT NULL REFERENCES category(category_id),
  brand         TEXT,
  model         TEXT NOT NULL,
  summary       TEXT,
  icon          TEXT,
  price         NUMERIC(12, 2),
  release_year  INTEGER,
  specs         JSONB NOT NULL DEFAULT '[]'::jsonb,
  provenance    TEXT NOT NULL DEFAULT 'manual'
                CHECK (provenance IN ('receipt', 'photo', 'manual')),
  confidence    TEXT CHECK (confidence IN ('high', 'medium', 'low')),
  status        TEXT NOT NULL DEFAULT 'owned'
                CHECK (status IN ('owned', 'retired', 'considering', 'sold')),
  acquired_at   TIMESTAMPTZ
);

CREATE TABLE product_cache (
  product_key     TEXT PRIMARY KEY,
  category_id     INTEGER NOT NULL REFERENCES category(category_id),
  brand           TEXT,
  model           TEXT NOT NULL,
  summary         TEXT,
  icon            TEXT,
  price           NUMERIC(12, 2),
  specs           JSONB NOT NULL DEFAULT '[]'::jsonb,
  source          TEXT NOT NULL,
  researched_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at      TIMESTAMPTZ
);

-- Search aliases for Decide free-text (e.g. "16 pro" → iPhone 16 Pro).
CREATE TABLE product_alias (
  alias_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_key   TEXT NOT NULL REFERENCES product_cache(product_key) ON DELETE CASCADE,
  alias         TEXT NOT NULL,
  source        TEXT NOT NULL DEFAULT 'seed',
  UNIQUE (alias)
);

CREATE TABLE decision (
  decision_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id                 INTEGER NOT NULL REFERENCES "user"(user_id) ON DELETE CASCADE,
  category_id             INTEGER REFERENCES category(category_id),
  query                   TEXT NOT NULL,
  branch                  TEXT NOT NULL
                          CHECK (branch IN (
                            'duplicate',
                            'upgrade',
                            'overlap_unknown',
                            'gap',
                            'unrecognised'
                          )),
  matched_item_id         INTEGER REFERENCES inventory_item(item_id) ON DELETE SET NULL,
  verdict                 TEXT NOT NULL
                          CHECK (verdict IN ('skip', 'wait', 'buy', 'clear')),
  stated_price            NUMERIC(12, 2),
  payload                 JSONB NOT NULL DEFAULT '{}'::jsonb,
  bought_against_advice   BOOLEAN NOT NULL DEFAULT FALSE,
  retired_item_id         INTEGER REFERENCES inventory_item(item_id) ON DELETE SET NULL,
  chosen_product_key      TEXT REFERENCES product_cache(product_key) ON DELETE SET NULL,
  purchased               BOOLEAN,
  created_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE recommendation_option (
  option_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  decision_id   INTEGER NOT NULL REFERENCES decision(decision_id) ON DELETE CASCADE,
  product_key   TEXT NOT NULL REFERENCES product_cache(product_key),
  was_chosen    BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX inventory_item_user_idx ON inventory_item (user_id);
CREATE INDEX inventory_item_user_cat_idx ON inventory_item (user_id, category_id);
CREATE INDEX inventory_item_status_idx ON inventory_item (user_id, status);
CREATE INDEX keyword_word_idx ON keyword (word);
CREATE INDEX product_alias_alias_idx ON product_alias (alias);
CREATE INDEX decision_user_idx ON decision (user_id, created_at DESC);
CREATE INDEX recommendation_decision_idx ON recommendation_option (decision_id);
CREATE INDEX product_cache_expires_idx ON product_cache (expires_at);

COMMENT ON COLUMN inventory_item.provenance IS
  'How we know this item: receipt | photo | manual (shown on Inventory rows).';
COMMENT ON COLUMN inventory_item.summary IS
  'Display subtitle e.g. "256 GB · Deep Purple" or "GaN · 3 ports".';
COMMENT ON COLUMN inventory_item.confidence IS
  'Intake confidence for photo/add flow: high | medium | low.';
COMMENT ON TABLE product_alias IS
  'Alternate names for classifier lookup. Local first; AI only on miss.';
COMMENT ON COLUMN decision.stated_price IS
  'Price the user typed on Decide (optional).';
COMMENT ON COLUMN decision.payload IS
  'Frozen verdict snapshot: head, rationale, meta, comparison, candidate.';
COMMENT ON COLUMN decision.bought_against_advice IS
  'True when purchased despite skip/wait: triggers sell-old-item nudge.';
COMMENT ON COLUMN decision.retired_item_id IS
  'Inventory item replaced when user bought an upgrade in same category.';
